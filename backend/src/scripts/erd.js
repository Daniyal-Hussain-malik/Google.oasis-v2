// Builds the ERD and the MySQL schema from the models, with no database connection needed.
//   npm run erd
// Writes backend/docs/erd.mmd (Mermaid), erd.dbml (dbdiagram.io), erd.md (preview) and
// backend/database/schema.sql (CREATE TABLE statements with every FOREIGN KEY).
//
// The tables now have real foreign keys, so an ERD tool pointed at the MySQL database
// draws the lines by itself. These files are for tools that do not connect to a database.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

process.env.DB_DIALECT = 'mysql';
const { sequelize } = await import('../config/db.js');
await import('../models/index.js');
const { LATE_FK } = await import('../db/schema.js');

const here = path.dirname(fileURLToPath(import.meta.url));
const docs = path.join(here, '..', '..', 'docs');
const dbDir = path.join(here, '..', '..', 'database');

const models = Object.values(sequelize.models).sort((a, b) => a.tableName.localeCompare(b.tableName));
const typeOf = (attribute) => String(attribute.type.key || attribute.type).replace(/\(.*/, '');

const tables = {}; // table -> [{ name, type, pk, fk, unique }]
const relations = []; // { from, field, to, toField, required }
for (const model of models) {
  const columns = [];
  for (const [name, attribute] of Object.entries(model.rawAttributes)) {
    const references = attribute.references;
    columns.push({
      name,
      type: typeOf(attribute),
      pk: Boolean(attribute.primaryKey),
      fk: Boolean(references) || (model.tableName === LATE_FK.table && name === LATE_FK.field),
      unique: Boolean(attribute.unique),
    });
    if (references) relations.push({ from: model.tableName, field: name, to: references.model, toField: references.key, required: attribute.allowNull === false });
  }
  tables[model.tableName] = columns;
}
relations.push({ from: LATE_FK.table, field: LATE_FK.field, to: LATE_FK.references.table, toField: LATE_FK.references.field, required: false });

const bad = relations.filter((r) => !tables[r.to]);
if (bad.length) throw new Error(`erd: links to unknown tables: ${bad.map((r) => `${r.from}.${r.field} -> ${r.to}`).join(', ')}`);

const names = Object.keys(tables);
const safe = (value) => value.replace(/[^A-Za-z0-9_]/g, '_');

// Mermaid
const mm = ['erDiagram'];
for (const name of names) {
  mm.push(`  ${name} {`);
  for (const c of tables[name]) mm.push(`    ${safe(c.type) || 'Mixed'} ${safe(c.name)}${c.pk ? ' PK' : c.fk ? ' FK' : c.unique ? ' UK' : ''}`);
  mm.push('  }');
}
const seen = new Set();
for (const r of relations) {
  const key = `${r.from}|${r.field}`;
  if (seen.has(key)) continue;
  seen.add(key);
  mm.push(`  ${r.to} ${r.required ? '||' : '|o'}--o{ ${r.from} : "${r.field}"`);
}
const mermaid = mm.join('\n');

// DBML
const db = [];
for (const name of names) {
  db.push(`Table ${name} {`);
  for (const c of tables[name]) {
    const flags = [c.pk ? 'pk' : '', c.unique ? 'unique' : ''].filter(Boolean).join(', ');
    db.push(`  "${c.name}" ${JSON.stringify(c.type)}${flags ? ` [${flags}]` : ''}`);
  }
  db.push('}', '');
}
for (const r of relations) db.push(`Ref: ${r.from}."${r.field}" > ${r.to}."${r.toField}"`);
const dbml = db.join('\n');

fs.mkdirSync(docs, { recursive: true });
fs.writeFileSync(path.join(docs, 'erd.mmd'), `${mermaid}\n`);
fs.writeFileSync(path.join(docs, 'erd.dbml'), `${dbml}\n`);
fs.writeFileSync(path.join(docs, 'erd.md'), `# Oasis Resort – data model (MySQL)\n\nGenerated by \`npm run erd\`. Do not edit by hand.\n\n\`\`\`mermaid\n${mermaid}\n\`\`\`\n`);

// erd.html: open it in a browser (needs internet once, for the Mermaid script). Keys only, so it stays readable.
const compact = ['erDiagram'];
for (const name of names) {
  compact.push(`  ${name} {`);
  for (const c of tables[name].filter((x) => x.pk || x.fk || x.unique)) compact.push(`    ${safe(c.type) || 'Mixed'} ${safe(c.name)}${c.pk ? ' PK' : c.fk ? ' FK' : ' UK'}`);
  compact.push('  }');
}
for (const line of mm.filter((l) => l.includes('--o{'))) compact.push(line);
const page = (title, code) => `<section><h2>${title}</h2><pre class="mermaid">
${code}
</pre></section>`;
fs.writeFileSync(path.join(docs, 'erd.html'), `<!doctype html><meta charset="utf-8"><title>Oasis Resort ER diagram</title>
<style>body{font-family:system-ui;margin:24px;background:#fff;color:#111}h2{margin-top:40px}pre.mermaid{overflow:auto;border:1px solid #ddd;padding:12px}</style>
<h1>Oasis Resort ER diagram (${names.length} tables, ${relations.length} foreign keys)</h1>
<p>Ctrl + scroll to zoom. Every line is a real FOREIGN KEY in MySQL.</p>
${page('Keys and links', compact.join(String.fromCharCode(10)))}
${page('All columns', mermaid)}
<script type="module">import mermaid from 'https://cdn.jsdelivr.net/npm/mermaid@10.9.1/dist/mermaid.esm.min.mjs';mermaid.initialize({startOnLoad:true,maxTextSize:900000,er:{useMaxWidth:false}});</script>`);

// schema.sql: ask Sequelize for the exact statements it would run, without connecting.
const statements = [];
const real = sequelize.query.bind(sequelize);
sequelize.query = async (sql) => {
  const text = typeof sql === 'string' ? sql : sql?.query || '';
  if (/^\s*(CREATE|ALTER)/i.test(text)) statements.push(text.trim().replace(/;?$/, ';'));
  return [[], 0];
};
let sqlNote = '';
try {
  await sequelize.sync();
  statements.push(
    `ALTER TABLE \`${LATE_FK.table}\` ADD CONSTRAINT \`${LATE_FK.name}\` FOREIGN KEY (\`${LATE_FK.field}\`) REFERENCES \`${LATE_FK.references.table}\` (\`${LATE_FK.references.field}\`) ON DELETE ${LATE_FK.onDelete} ON UPDATE CASCADE;`,
  );
} catch (error) {
  sqlNote = `-- Could not generate statements: ${error.message}\n`;
}
sequelize.query = real;
fs.mkdirSync(dbDir, { recursive: true });
fs.writeFileSync(
  path.join(dbDir, 'schema.sql'),
  `-- Oasis Resort: MySQL 8 schema. Generated by \`npm run erd\` from the models.\n-- Create the database first:  CREATE DATABASE oasis_resort CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;\n-- The server also creates missing tables by itself on start (npm run db:setup does the same).\n\nSET FOREIGN_KEY_CHECKS = 0;\n${sqlNote}${statements.join('\n\n')}\nSET FOREIGN_KEY_CHECKS = 1;\n`,
);

console.log(`${names.length} tables, ${relations.length} foreign keys`);
console.log(`Written: docs/erd.html, docs/erd.mmd, docs/erd.dbml, docs/erd.md, database/schema.sql (${statements.length} statements)`);
const linked = new Set(relations.flatMap((r) => [r.from, r.to]));
const alone = names.filter((n) => !linked.has(n));
if (alone.length) console.log(`Tables with no links (standalone by design): ${alone.join(', ')}`);
process.exit(0);
